/** Theme for a sign (0-11) and Sabian degree (1-30). */
export function sabianTheme(signIndex: number, degree: number): string {
  return S[signIndex][degree - 1];
}

export const SABIAN_COUNT = S.reduce((n, sign) => n + sign.length, 0);
